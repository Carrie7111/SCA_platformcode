# 主实现类，完全对应 Java 代码
class AesSinXorSoutAnalysisDefault(AesSinXorSoutAnalysisBase):
    """
    AES S盒汉明距离攻击分析
    功能、逻辑、计算结果与原Java代码完全一致
    """

    def GetMidDataHW(self, data):
        """
        核心方法：1:1还原Java逻辑
        :param data: 输入字节数组（长度必须为16）
        :return: 长度4096的浮点数组，存储汉明距离
        """
        # 空值判断，与Java完全一致
        if data is None:
            return None

        # 初始化4096长度浮点数组（Java float[]）
        MidDataHW = [0.0] * 4096
        # 初始化16字节临时数组
        tem = bytearray(16)

        # 循环：猜测密钥 i 0~255
        for i in range(256):
            # 第一步：data[j] ^ i 赋值到临时数组
            for j in range(16):
                tem[j] = data[j] ^ i

            # 第二步：计算S盒输入输出异或后的汉明重量
            for j in range(16):
                s_in = tem[j]
                # 核心计算：Aes.S[s_in] ^ s_in → 取无符号 → 计算汉明重量
                s_box_val = Aes.S[s_in & 0xFF]
                xor_val = s_box_val ^ s_in
                index = i + 256 * j
                # 赋值为浮点数，与Java一致
                MidDataHW[index] = float(self.GetHW(xor_val & 0xFF))

        return MidDataHW

    def GetHW(self, value):
        """
        汉明重量计算（二进制中1的个数）
        与父类 AesSinXorSoutAnalysisBase 中的方法一致
        """
        return bin(value).count('1')